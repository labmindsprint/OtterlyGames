export function academyPages(origin = 'https://otterlygames.com') {
  return [
    { route: COLLECTION, html: collectionPage(origin) },
    ...GRADES.flatMap(grade => [
      { route: gradeRoute(grade), html: gradePage(grade, origin) },
      ...grade.chapters.map(chapter => ({ route: chapterRoute(grade.id, chapter.id), html: chapterPage(grade, chapter, origin) })),
    ]),
  ];
}

export function buildAcademy({ root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), write = false } = {}) {
  const inventory = validateInventory(JSON.parse(readFileSync(join(root, '_data', 'public-pages.json'), 'utf8')));
  const templates = {
    nav: readFileSync(join(root, '_includes', 'nav.html'), 'utf8').trim(),
    footer: readFileSync(join(root, '_includes', 'footer.html'), 'utf8').trim(),
  };
  validateTemplates(templates);
  const pages = academyPages(inventory.origin);
  const routes = new Set(pages.map(page => page.route));
  const inventoried = new Set(inventory.pages.map(page => page.route));
  for (const route of routes) {
    if (!inventoried.has(route)) throw new Error(`Add ${route} explicitly to _data\\public-pages.json before generating it.`);
  }
  for (const route of inventoried) {
    if (route.startsWith(COLLECTION) && !routes.has(route)) throw new Error(`Unknown Academy discovery route in the public inventory: ${route}`);
  }
  const changes = [];
  for (const page of pages) {
    const target = join(root, ...page.route.slice(1).split('/'), ...(page.route.endsWith('/') ? ['index.html'] : []));
    const before = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (before !== null && !before.includes(GENERATED)) throw new Error(`Refusing to overwrite an unrecognised Academy page: ${target}`);
    const after = transformPublicPage(page.html, { route: page.route }, { templates, origin: inventory.origin }).html;
    if (before !== after) changes.push({ target, after });
  }
  if (write) {
    for (const change of changes) {
      mkdirSync(dirname(change.target), { recursive: true });
      writeFileSync(change.target, change.after, 'utf8');
    }
  }
  return { pages: pages.length, changed: changes.length, files: changes.map(change => change.target) };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 1 || args.some(arg => !['--write', '--check'].includes(arg))) throw new Error('Use --write or --check (default).');
    const write = args[0] === '--write';
    const result = buildAcademy({ write });
    if (!write && result.changed) {
      console.error(`Academy discovery is stale (${result.changed} pages). Run node .\\scripts\\build-space-academy.mjs --write.`);
      process.exitCode = 1;
    } else console.log(`${write ? 'Generated' : 'Checked'} ${result.pages} Academy discovery pages; ${result.changed} ${write ? 'updated' : 'stale'}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
