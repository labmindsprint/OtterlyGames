function sourceChapter(cls, chapter) {
  const id = chapter.source ?? `${cls.id}/${chapter.id}`;
  const [grade, chapterId] = id.split('/');
  try { getChapter(grade, chapterId); return { grade, chapterId }; } catch (error) { return null; }
}

