const fileFor = (root, route) => join(root, ...route.slice(1).split('/'), ...(route.endsWith('/') ? ['index.html'] : []));

const ROUTE_LINE = /^    \{ "route": "\/learn\/maths\/[^"]*" \},?\r?\n/gm;

// Rewrites the contiguous /learn/maths/ block of _data/public-pages.json so it matches the generated pages.
export function syncInventoryText(text, routes) {
  const lines = [...text.matchAll(ROUTE_LINE)];
  if (!lines.length) throw new Error('_data/public-pages.json needs at least one /learn/maths/ entry to anchor the Maths Path block.');
  const start = lines[0].index;
  const end = lines.at(-1).index + lines.at(-1)[0].length;
  const eol = text.includes('\r\n') ? '\r\n' : '\n';
  const block = routes.map((route) => `    { "route": "${route}" },${eol}`).join('');
  return text.slice(0, start) + block + text.slice(end);
}

const PICK = /<!-- mp:pick:start -->[\s\S]*?<!-- mp:pick:end -->/;
export function pickList(data) {
  const items = data.classes.map((cls) => `        <li${cls.live ? ' class="is-live"' : ''}><a href="${classRoute(cls)}"><strong>${e(cls.label)}</strong><small>${cls.live ? `${cls.chapters.length} lessons ready` : `Plan: ${cls.chapters.length} chapters`}</small></a></li>`).join('\n');
  return `<!-- mp:pick:start -->\n      <ul class="mp-pick">\n${items}\n      </ul>\n      <!-- mp:pick:end -->`;
}

export function buildMathsPath({ root = resolve(dirname(fileURLToPath(import.meta.url)), '..'), write = false, syncInventory = false } = {}) {
  const data = loadData(root);
  const problems = dataProblems(data, { root });
  if (problems.length) throw new Error(`Maths Path data problems (${problems.length}):\n${problems.join('\n')}`);
  const inventoryFile = join(root, '_data', 'public-pages.json');
  if (syncInventory) {
    const routes = mathsPages(data).map((p) => p.route);
    const before = readFileSync(inventoryFile, 'utf8');
    const after = syncInventoryText(before, routes);
    if (after !== before) writeFileSync(inventoryFile, after, 'utf8');
  }
  const inventory = validateInventory(JSON.parse(readFileSync(inventoryFile, 'utf8')));
  const templates = { nav: readFileSync(join(root, '_includes', 'nav.html'), 'utf8').trim(), footer: readFileSync(join(root, '_includes', 'footer.html'), 'utf8').trim() };
  validateTemplates(templates);
  const inventoried = new Set(inventory.pages.map((p) => p.route));
  const outputs = [];
  for (const page of mathsPages(data, inventory.origin)) {
    if (!inventoried.has(page.route)) throw new Error(`${page.route} is missing from _data\\public-pages.json. Run node .\\scripts\\build-maths-path.mjs --sync-inventory --write.`);
    outputs.push({ route: page.route, html: transformPublicPage(page.html, { route: page.route }, { templates, origin: inventory.origin }).html });
  }
  const seo = outputs.flatMap((o) => seoProblems(o.html, o.route, inventory.origin));
  if (seo.length) throw new Error(`Maths Path SEO problems:\n${seo.join('\n')}`);
  for (const route of inventoried) {
    if (route.startsWith(HUB) && !outputs.some((o) => o.route === route)) throw new Error(`Unknown Maths Path route in the public inventory: ${route}`);
  }
  outputs.push(...redirectPages(data, inventory.origin).map((p) => ({ route: p.route, html: p.html })));
  const changes = [];
  for (const out of outputs) {
    const target = fileFor(root, out.route);
    const before = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (before !== null && !before.includes(GENERATED) && !before.includes('<!-- Generated by scripts/build-space-academy.mjs.')) {
      throw new Error(`Refusing to overwrite an unrecognised page: ${target}`);
    }
    if (before?.replaceAll('\r\n', '\n') !== out.html.replaceAll('\r\n', '\n')) changes.push({ target, after: out.html });
  }
  const learnFile = join(root, 'learn', 'index.html');
  const learnBefore = readFileSync(learnFile, 'utf8');
  if (!PICK.test(learnBefore)) throw new Error('learn/index.html needs the <!-- mp:pick:start --> ... <!-- mp:pick:end --> markers around the class picker.');
  const eol = learnBefore.includes('\r\n') ? '\r\n' : '\n';
  const learnAfter = learnBefore.replace(PICK, (block) => (block.replaceAll('\r\n', '\n') === pickList(data) ? block : pickList(data).replaceAll('\n', eol)));
  if (learnAfter !== learnBefore) changes.push({ target: learnFile, after: learnAfter });
  if (write) {
    for (const change of changes) {
      mkdirSync(dirname(change.target), { recursive: true });
      writeFileSync(change.target, change.after, 'utf8');
    }
  }
  return { pages: outputs.length, changed: changes.length, files: changes.map((c) => c.target), outputs };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args.length > 2 || args.some((arg) => !['--write', '--check', '--sync-inventory'].includes(arg))) throw new Error('Use --write or --check (default); add --sync-inventory to update _data/public-pages.json first.');
    const write = args.includes('--write');
    const result = buildMathsPath({ write, syncInventory: args.includes('--sync-inventory') });
    if (!write && result.changed) {
      console.error(`Maths Path pages are stale (${result.changed}). Run node .\\scripts\\build-maths-path.mjs --write.`);
      process.exitCode = 1;
    } else console.log(`${write ? 'Generated' : 'Checked'} ${result.pages} Maths Path pages; ${result.changed} ${write ? 'updated' : 'stale'}.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
